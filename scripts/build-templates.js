// Run after editing index.html or shop.html: node scripts/build-templates.js
// Embedding templates keeps Netlify functions independent of runtime file paths.
const fs=require('node:fs');
const path=require('node:path');
const root=path.resolve(__dirname,'..');
function read(name){return fs.readFileSync(path.join(root,name),'utf8').replace(/((?:src|href)=")(images\/|css\/|js\/|supabase-client\.js|manifest\.json)/g,'$1/$2');}
const shop=read('shop.html');
const prefix=shop.slice(0,shop.indexOf('<header class="page-header">'));
const suffix=shop.slice(shop.indexOf('<div class="newsletter">')).replace(/\/js\/shop\.js(?=[?"'])/g,'/js/collection-page.js');
fs.writeFileSync(path.join(root,'netlify/lib/templates.js'),'// Generated by scripts/build-templates.js. Edit the source HTML.\nmodule.exports = '+JSON.stringify({shell:prefix+'<!--PAGE_CONTENT-->'+suffix,home:read('index.html')})+';\n');
